// ── Deterministic Rule Evaluation Function ─────────────────────────────────

function evaluateSymptoms({ symptoms, duration, severity }) {
  const normalizedInputs = symptoms.map((s) => s.trim().toLowerCase());
  const combinedInputText = normalizedInputs.join(' | ');

  // 1. Check emergency red-flag triggers
  const matchedEmergencies = [];
  for (const trigger of EMERGENCY_TRIGGERS) {
    const matchedKeywords = trigger.keywords.filter((kw) =>
      normalizedInputs.some((input) => input.includes(kw)) || combinedInputText.includes(kw)
    );
    if (matchedKeywords.length > 0) {
      matchedEmergencies.push({
        category: trigger.category,
        matched_terms: matchedKeywords,
      });
    }
  }

  const hasEmergencyWarning = matchedEmergencies.length > 0;

  // 2. Match standard symptom categories
  const matchedCategories = [];
  const educationalDetails = [];
  const selfCareSet = new Set();
  const seekCareSet = new Set();

  for (const rule of SYMPTOM_RULES) {
    const matchedKeywords = rule.keywords.filter((kw) =>
      normalizedInputs.some((input) => input.includes(kw)) || combinedInputText.includes(kw)
    );
    if (matchedKeywords.length > 0) {
      matchedCategories.push({
        id: rule.id,
        category: rule.category,
        matched_keywords: matchedKeywords,
      });
      educationalDetails.push({
        category: rule.category,
        information: rule.educational_info,
      });
      rule.self_care.forEach((item) => selfCareSet.add(item));
      rule.when_to_seek_care.forEach((item) => seekCareSet.add(item));
    }
  }

  // Fallback for unrecognized symptoms
  if (matchedCategories.length === 0) {
    matchedCategories.push({
      id: 'general_unclassified',
      category: 'General / Unclassified Symptom Inquiry',
      matched_keywords: [],
    });
    educationalDetails.push({
      category: 'General Health Inquiry',
      information:
        'The entered symptom(s) did not match a specific pre-configured rule in our local keyword catalog. Symptoms can vary widely depending on personal health history, duration, and context.',
    });
    selfCareSet.add('Rest in a comfortable position and monitor whether your symptoms change or progress.');
    selfCareSet.add('Maintain normal hydration with water unless advised otherwise by a clinician.');
    selfCareSet.add('Keep a written log of when the symptoms started, their severity, and any triggers to share with a healthcare provider.');
    seekCareSet.add('Consult a licensed healthcare provider or pharmacist for personalized evaluation of any unfamiliar, persistent, or concerning symptoms.');
    seekCareSet.add('Seek prompt medical care if symptoms worsen rapidly, interfere with daily activities, or cause significant distress.');
  }

  // Add severity / duration contextual educational notes
  if (severity === 'severe') {
    seekCareSet.add('Because you marked the symptom severity as SEVERE, prompt evaluation by a qualified healthcare professional is strongly recommended.');
  }
  if (duration) {
    educationalDetails.push({
      category: 'Reported Duration & Severity Context',
      information: `You reported a duration of "${duration}" with "${severity}" severity. Sharing exact timelines and severity changes helps a clinician evaluate your symptoms accurately.`,
    });
  }

  const emergencyAlert = hasEmergencyWarning
    ? {
        is_emergency_warning: true,
        warning_level: 'HIGH_PRIORITY_SAFETY_NOTICE',
        headline: 'IMPORTANT SAFETY NOTICE: Potential Emergency Symptom Keywords Detected',
        message:
          'One or more of the symptoms you entered (such as chest pain, breathing difficulty, stroke-like symptoms, or loss of consciousness) can be associated with serious medical emergencies. This rule-based tool CANNOT diagnose conditions or reliably triage emergencies. If you or someone else may be experiencing a medical emergency, call your local emergency number (e.g., 911) or go to the nearest emergency department immediately.',
        matched_emergency_categories: matchedEmergencies,
      }
    : {
        is_emergency_warning: false,
        warning_level: 'STANDARD_SAFETY_NOTICE',
        headline: 'Standard Non-Emergency Educational Output',
        message:
          'No pre-configured emergency red-flag keywords were matched, but this deterministic rule engine cannot rule out urgent medical conditions. If you experience chest pain, severe breathing difficulty, sudden weakness/numbness, confusion, or fainting, seek emergency medical care immediately.',
        matched_emergency_categories: [],
      };

  return {
    engine_type: 'deterministic_rule_engine_v1',
    engine_statement: ENGINE_NOTICE,
    emergency_safety: emergencyAlert,
    matched_categories: matchedCategories,
    educational_information: educationalDetails,
    self_care_tips: Array.from(selfCareSet),
    when_to_seek_medical_advice: Array.from(seekCareSet),
    submitted_context: {
      symptoms,
      duration: duration || null,
      severity,
    },
    disclaimer: MEDICAL_DISCLAIMER,
  };
}

// ── Joi Validation Schemas ─────────────────────────────────────────────────

const checkSymptomsSchema = Joi.object({
  symptoms: Joi.array()
    .items(Joi.string().trim().min(1).max(120))
    .min(1)
    .max(20)
    .required()
    .messages({
      'array.base': 'symptoms must be an array of symptom strings',
      'array.min': 'At least one symptom must be provided',
      'string.empty': 'Symptom strings cannot be empty',
    }),
  duration: Joi.string().trim().max(100).allow(null, '').default(null),
  severity: Joi.string()
    .valid('mild', 'moderate', 'severe')
    .default('mild')
    .messages({
      'any.only': 'severity must be one of [mild, moderate, severe]',
    }),
  patient_id: Joi.number()
    .integer()
    .positive()
    .allow(null)
    .default(null)
    .messages({
      'number.base': 'patient_id must be a valid positive integer',
      'number.integer': 'patient_id must be an integer',
      'number.positive': 'patient_id must be a positive integer',
    }),
});

const historyQuerySchema = Joi.object({
  page: Joi.number().integer().min(1).default(1),
  limit: Joi.number().integer().min(1).max(100).default(10),
  patient_id: Joi.number().integer().positive().optional().messages({
    'number.base': 'patient_id filter must be a positive integer',
    'number.integer': 'patient_id filter must be an integer',
    'number.positive': 'patient_id filter must be a positive integer',
  }),
});

// ── Route Handlers ─────────────────────────────────────────────────────────

/**
 * POST /api/symptoms/check
 * Evaluate symptoms using deterministic rule engine and persist to symptom_checks.
 */
router.post(
  '/check',
  validate(checkSymptomsSchema, 'body'),
  asyncHandler(async (req, res) => {
    const db = getDb();
    const { symptoms, duration, severity, patient_id } = req.body;
    const normalizedDuration = duration === '' ? null : duration;

    // Verify patient_id exists if provided
    let patientRecord = null;
    if (patient_id !== null && patient_id !== undefined) {
      patientRecord = db
        .prepare('SELECT id, first_name, last_name FROM patients WHERE id = ?')
        .get(patient_id);
      if (!patientRecord) {
        const err = new Error(`Demo patient with ID ${patient_id} not found`);
        err.status = 404;
        throw err;
      }
    }

    const evaluation = evaluateSymptoms({
      symptoms,
      duration: normalizedDuration,
      severity,
    });

    const insertStmt = db.prepare(`
      INSERT INTO symptom_checks (
        patient_id, symptoms, duration, severity, response, disclaimer
      ) VALUES (
        @patient_id, @symptoms, @duration, @severity, @response, @disclaimer
      )
    `);

    const info = insertStmt.run({
      patient_id: patient_id ?? null,
      symptoms: JSON.stringify(symptoms),
      duration: normalizedDuration,
      severity,
      response: JSON.stringify(evaluation),
      disclaimer: MEDICAL_DISCLAIMER,
    });

    const savedRow = db
      .prepare('SELECT * FROM symptom_checks WHERE id = ?')
      .get(info.lastInsertRowid);

    return res.status(201).json({
      success: true,
      meta: {
        demo_notice: DEMO_NOTICE,
        engine_notice: ENGINE_NOTICE,
      },
      data: {
        id: savedRow.id,
        patient_id: savedRow.patient_id,
        patient: patientRecord,
        symptoms,
        duration: savedRow.duration,
        severity: savedRow.severity,
        evaluation,
        disclaimer: savedRow.disclaimer,
        created_at: savedRow.created_at,
      },
    });
  })
);

/**
 * GET /api/symptoms/history
 * Retrieve paginated symptom-check history with optional patient_id filter.
 */
router.get(
  '/history',
  validate(historyQuerySchema, 'query'),
  asyncHandler(async (req, res) => {
    const db = getDb();
    const { page, limit, patient_id } = req.validatedQuery;
    const offset = (page - 1) * limit;

    let total;
    let rows;

    if (patient_id !== undefined) {
      // Check if the filtered patient exists
      const patientExists = db.prepare('SELECT id FROM patients WHERE id = ?').get(patient_id);
      if (!patientExists) {
        const err = new Error(`Demo patient with ID ${patient_id} not found`);
        err.status = 404;
        throw err;
      }

      total = db
        .prepare('SELECT COUNT(*) AS count FROM symptom_checks WHERE patient_id = @patient_id')
        .get({ patient_id }).count;

      rows = db
        .prepare(`
          SELECT sc.*, p.first_name AS patient_first_name, p.last_name AS patient_last_name
          FROM symptom_checks sc
          LEFT JOIN patients p ON sc.patient_id = p.id
          WHERE sc.patient_id = @patient_id
          ORDER BY sc.id DESC
          LIMIT @limit OFFSET @offset
        `)
        .all({ patient_id, limit, offset });
    } else {
      total = db.prepare('SELECT COUNT(*) AS count FROM symptom_checks').get().count;

      rows = db
        .prepare(`
          SELECT sc.*, p.first_name AS patient_first_name, p.last_name AS patient_last_name
          FROM symptom_checks sc
          LEFT JOIN patients p ON sc.patient_id = p.id
          ORDER BY sc.id DESC
          LIMIT @limit OFFSET @offset
        `)
        .all({ limit, offset });
    }

    const formattedChecks = rows.map((row) => {
      let parsedSymptoms = [];
      let parsedEvaluation = null;
      try {
        parsedSymptoms = JSON.parse(row.symptoms);
      } catch (_e) {
        parsedSymptoms = [row.symptoms];
      }
      try {
        parsedEvaluation = JSON.parse(row.response);
      } catch (_e) {
        parsedEvaluation = { raw: row.response };
      }

      return {
        id: row.id,
        patient_id: row.patient_id,
        patient_name:
          row.patient_first_name && row.patient_last_name
            ? `${row.patient_first_name} ${row.patient_last_name}`
            : null,
        symptoms: parsedSymptoms,
        duration: row.duration,
        severity: row.severity,
        evaluation: parsedEvaluation,
        disclaimer: row.disclaimer,
        created_at: row.created_at,
      };
    });

    const totalPages = Math.ceil(total / limit) || 1;

    return res.status(200).json({
      success: true,
      meta: {
        demo_notice: DEMO_NOTICE,
        engine_notice: ENGINE_NOTICE,
      },
      data: {
        checks: formattedChecks,
        pagination: {
          total,
          page,
          limit,
          total_pages: totalPages,
          has_next: page < totalPages,
          has_prev: page > 1,
        },
      },
    });
  })
);

